import { additionalLogic } from '../logic-expansion.js';
import { questionDuration, EXTRA_TIME_MS } from '../timing.js';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
import { topics } from '../questions.js';
import { drills } from '../study.js';
import { reviewBank } from '../review-bank.js';
import { emptyLibrary, loadLibrary, saveLibrary, snapshotGame, restoreGame, addCampaign, updateCampaign, removeCampaign } from '../campaign-storage.js';
const src = fs.readFileSync(new URL('../src.jsx', import.meta.url), 'utf8');
const context = vm.createContext({ additionalLogic, questionDuration, EXTRA_TIME_MS,topics, drills, reviewBank, Landmark: null, Lightbulb: null, Layers: null, Globe: null, Scale: null, Eye: null, Bomb: null, RotateCcw: null, CircleCheck: null, Timer: null});
vm.runInContext(src.slice(src.indexOf('const levelCount'), src.indexOf('function CrownProgress')) + '\nglobalThis.api = {start, reducer, createCampaign, levelQuestions};', context);
const { start, reducer, createCampaign, levelQuestions } = context.api;
const makeGame = () => { const deck = createCampaign(); return start(deck, 0, levelQuestions(deck, 0)); };
const data = new Map();
const storage = { getItem: key => data.get(key) ?? null, setItem: (key, value) => data.set(key, value) };
assert.deepEqual(loadLibrary(storage).library, emptyLibrary());
let a = makeGame();
a = reducer(a, {type: 'spin', random: [0], now: 1000});
a = reducer(a, {type: 'land', now: 1000});
a = reducer(a, {type: 'begin', now: 1000});
a = reducer(a, {type: 'power', power: 'retry', now: 2000});
const wrong = (a.questions[a.index][2] + 1) % 4;
a = reducer(a, {type: 'answer', choice: wrong, now: 3000});
let library = addCampaign(emptyLibrary(), 'Primera', a, 6000, 'first');
const originalQuestions = JSON.stringify(library.campaigns[0].snapshot.questions);
assert.equal(library.campaigns[0].snapshot.remainingMs, 55000);
assert.equal(saveLibrary(library, storage), '');
let loaded = loadLibrary(storage);
assert.equal(loaded.error, '');
assert.equal(loaded.library.campaigns.length, 1);
let restored = restoreGame(loaded.library.campaigns[0].snapshot, 1000000);
assert.equal(restored.pausedAt, 1000000);
assert.equal(restored.stock.retry, 0);
assert.equal(restored.wrong, wrong);
assert.equal(restored.used, 'retry');
assert.equal(JSON.stringify(restored.questions), originalQuestions);
restored = reducer(restored, {type: 'resume', now: 1100000});
assert.equal(restored.deadline - 1100000, 55000);
restored = reducer(restored, {type: 'answer', choice: restored.questions[restored.index][2], now: 1101000});
assert.equal(restored.score, 1);
assert.equal(restored.xp, 10);
library = updateCampaign(loaded.library, 'first', restored, 1101000);
const firstBefore = JSON.stringify(library.campaigns[0]);
library = addCampaign(library, 'Segunda', makeGame(), 1200000, 'second');
assert.equal(JSON.stringify(library.campaigns[0]), firstBefore);
assert.equal(saveLibrary(library, storage), '');
loaded = loadLibrary(storage);
assert.equal(loaded.library.campaigns.length, 2);
assert.equal(loaded.library.activeId, 'second');
// Reloading feedback never adds the correct answer or its XP a second time.
const feedback = restoreGame(loaded.library.campaigns[0].snapshot, 2000000);
assert.equal(feedback.phase, 'feedback');
assert.equal(feedback.score, 1);
assert.equal(feedback.xp, 10);
// Repetition retains the question selection of all ten levels, resets progress, and leaves the original intact.
const repeated = start(feedback.campaign, 0, levelQuestions(feedback.campaign, 0));
library = addCampaign(library, 'Repetición', repeated, 3000000, 'repeat');
assert.equal(repeated.score, 0);
assert.equal(repeated.xp, 0);
assert.equal(repeated.levelResults.length, 0);
assert.equal(JSON.stringify(repeated.campaign), JSON.stringify(feedback.campaign));
assert.equal(JSON.stringify(library.campaigns[0]), firstBefore);
const withThird = library.campaigns[2];
library = removeCampaign(library, 'second');
assert.equal(library.campaigns.length, 2);
assert.equal(library.campaigns[0].id, 'first');
assert.equal(library.campaigns[1], withThird);
library = removeCampaign(library, 'repeat');
assert.equal(library.activeId, null);
assert.equal(library.campaigns.length, 1);
// A paused question keeps the remaining time even if it is saved much later.
const paused = reducer(a, {type: 'pause', now: 6000});
assert.equal(snapshotGame(paused, 999999).remainingMs, 55000);
// Restoring a spin lands in its already selected category rather than selecting another question.
const spinning = reducer(makeGame(), {type: 'spin', random: [0], now: 1000});
const landed = restoreGame(snapshotGame(spinning, 1500), 999999);
assert.equal(landed.phase, 'topic');
assert.equal(landed.index, spinning.index);
// Save and reload after every level; all ten results and their XP must survive.
let completedGame = makeGame();
for (let level = 0; level < 10; level++) {
  let steps = 0;
  while (completedGame.phase !== 'summary') {
    assert.ok(steps++ < 200);
    const phase = completedGame.phase;
    const action = phase === 'wheel' ? {type: 'spin', random: [0]} : phase === 'spinning' ? {type: 'land'} : phase === 'topic' ? {type: 'begin'} : phase === 'question' ? {type: 'answer', choice: completedGame.questions[completedGame.index][2]} : phase === 'offer' ? {type: 'skip'} : {type: 'next'};
    completedGame = reducer(completedGame, {...action, now: 1000});
  }
  const savedLevels = addCampaign(emptyLibrary(), 'Historial', completedGame, 4000000, 'history');
  assert.equal(saveLibrary(savedLevels, storage), '');
  const historyLoad = loadLibrary(storage);
  assert.equal(historyLoad.error, '');
  assert.equal(historyLoad.library.campaigns[0].snapshot.levelResults.length, level + 1);
  completedGame = restoreGame(historyLoad.library.campaigns[0].snapshot, 5000000);
  completedGame = reducer(completedGame, {type: 'resume', now: 5000000});
  assert.equal(completedGame.xp, 380 * (level + 1));
  if (level < 9) completedGame = reducer(completedGame, {type: 'level', levelDeck: levelQuestions(completedGame.campaign, level + 1)});
}
assert.equal(completedGame.levelResults.length, 10);
assert.equal(completedGame.xp, 3800);
// A second-chance replacement also restores its exact options and reservation.
let replacement = makeGame();
replacement = reducer(replacement, {type: 'spin', random: [0], now: 1000});
replacement = reducer(replacement, {type: 'land', now: 1000});
replacement = reducer(replacement, {type: 'begin', now: 1000});
replacement = reducer(replacement, {type: 'answer', choice: (replacement.questions[replacement.index][2] + 1) % 4, now: 2000});
const replacementQuestion = ['Nueva pregunta', ['A', 'B', 'C', 'D'], 2, replacement.questions[replacement.index][3]];
replacement = reducer(replacement, {type: 'secondChance', levelDeck: replacementQuestion, now: 3000});
const withReplacement = addCampaign(emptyLibrary(), 'Reemplazo', replacement, 4000, 'replacement');
assert.equal(saveLibrary(withReplacement, storage), '');
assert.equal(loadLibrary(storage).error, '');
const restoredReplacement = restoreGame(loadLibrary(storage).library.campaigns[0].snapshot, 1000000);
assert.deepEqual(restoredReplacement.replacements[restoredReplacement.index], replacementQuestion);
assert.equal(restoredReplacement.secondChance, false);
assert.equal(restoredReplacement.deadline - 1000000, 59000);
// Existing campaigns get the longer allowance once; re-saving must not add it again.
const legacy = { ...snapshotGame(a, 6000), remainingMs: 15000 };
delete legacy.timerVersion;
const upgraded = restoreGame(legacy, 1000000);
assert.equal(upgraded.deadline - 1000000, 55000);
const savedUpgrade = snapshotGame(upgraded, 1100000);
assert.equal(restoreGame(savedUpgrade, 2000000).deadline - 2000000, 55000);
assert.equal(questionDuration('Lógica y ética'), 90000);
assert.equal(questionDuration('Filosofía moderna'), 60000);
// Old summaries lacking crowns reopen with earned answers intact and without the unearned bonus.
const incomplete = { ...snapshotGame(a, 6000), phase: 'summary', solved: Array.from({length: 24}, (_, i) => i), xp: 50, levelResults: [{level: 1, score: 0, crowns: []}] };
delete incomplete.levelRuleVersion;
const oldLibrary = { version: 1, activeId: 'old', campaigns: [{id: 'old', name: 'Anterior', createdAt: 1, updatedAt: 2, snapshot: incomplete}] };
storage.setItem([...data.keys()][0], JSON.stringify(oldLibrary));
const migrated = loadLibrary(storage);
assert.equal(migrated.error, '');
const reopened = migrated.library.campaigns[0].snapshot;
assert.equal(reopened.phase, 'wheel');
assert.equal(reopened.solved.length, 0);
assert.equal(reopened.xp, 0);
assert.equal(reopened.levelResults.length, 0);
assert.equal(saveLibrary(migrated.library, storage), '');
assert.equal(loadLibrary(storage).library.campaigns[0].snapshot.xp, 0);
// Damaged data is detected and retained before a new valid save replaces it.
const key = [...data.keys()][0];
storage.setItem(key, '{broken');
assert.ok(loadLibrary(storage).error);
assert.equal(storage.getItem(key), '{broken');
assert.equal(saveLibrary(library, storage), '');
assert.equal(storage.getItem(key + '.recovery'), '{broken');
assert.equal(loadLibrary(storage).error, '');
const blocked = { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } };
assert.ok(loadLibrary(blocked).error);
assert.ok(saveLibrary(library, blocked));
const quota = { getItem: storage.getItem, setItem() { throw Error('quota'); } };
assert.ok(saveLibrary(library, quota));
console.log('PASS: local campaign round trips, independent campaigns, timer and powers, feedback without duplicate XP, repeat, delete, corrupt/blocked storage and quota errors.');
